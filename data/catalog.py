ALL_FUNCTIONS = []
for dept in DEPARTMENTS:
    for fn in dept["functions"]:
        ALL_FUNCTIONS.append({"dept_id": dept["id"], "name": fn})

def get_department(dept_id):
    for d in DEPARTMENTS:
        if d["id"] == dept_id:
            return d
    return None

def get_functions_for_department(dept_id):
    d = get_department(dept_id)
    return d["functions"] if d else []
